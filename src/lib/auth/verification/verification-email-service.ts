import 'server-only';

import {
	DeviceApprovalEmail,
	MailError
} from '@assosync/email';
import { createElement } from 'react';
import type {
	SendVerificationEmailInput,
	VerificationEmailBrand,
	VerificationEmailResult,
	VerificationEmailSender,
	VerificationEmailServiceOptions
} from '@/types/auth';

/** Composes and sends new-device verification emails. */
class VerificationEmailService {
	/** Application-specific email configurations. */
	private readonly brands: ReadonlyMap<
		string,
		VerificationEmailBrand
	>;

	/**
	 * Creates a verification email service.
	 * @param emails - Generic transactional email sender.
	 * @param options - Application-specific email configurations.
	 * @throws {MailError} When the configuration is invalid.
	 */
	constructor(
		private readonly emails: VerificationEmailSender,
		options: VerificationEmailServiceOptions
	) {
		this.brands = new Map(
			options.brands.map((brand) => {
				return [
					brand.applicationId,
					brand
				];
			})
		);

		if (
			this.brands.size === 0 ||
			this.brands.size !== options.brands.length
		) {
			throw new MailError(
				'config_invalid',
				'Verification email brands must be non-empty and unique.'
			);
		}

		for (const brand of options.brands) {
			if (
				!brand.applicationId.trim() ||
				!brand.displayName.trim() ||
				!brand.from.trim()
			) {
				throw new MailError(
					'config_invalid',
					'The verification email brand configuration is invalid.'
				);
			}
		}
	}

	/**
	 * Sends a code generated by the verification service.
	 * @param input - Issued verification and verified Firebase recipient.
	 * @returns The accepted provider message.
	 * @throws {MailError} When the input or delivery fails.
	 */
	readonly send = async (
		input: SendVerificationEmailInput
	): Promise<VerificationEmailResult> => {
		const {
			verification,
			emailCode
		} = input.issued;

		const brand = this.brands.get(
			verification.applicationId
		);

		const firstname = input.firstname?.trim();
		const recipient = input.to.trim();

		const validityMs = (
			verification.expiresAt.getTime() -
			verification.createdAt.getTime()
		);

		if (
			!brand ||
			!recipient ||
			!Number.isSafeInteger(validityMs) ||
			validityMs <= 0
		) {
			throw new MailError(
				'input_invalid',
				'The device verification email input is invalid.'
			);
		}

		const formattedCode = [
			emailCode.slice(0, 3),
			emailCode.slice(3)
		].join(' ');

		const expirationMinutes = Math.max(
			1,
			Math.ceil(validityMs / 60_000)
		);

		const email = createElement(
			DeviceApprovalEmail,
			{
				...(firstname
					? {
						firstname
					}
					: {}),
				code: formattedCode,
				expirationMinutes,
				type: brand.emailType
			}
		);

		return this.emails.send({
			from: brand.from,
			to: [recipient],
			subject:
				`Confirmez ce nouvel appareil sur ${brand.displayName}`,
			react: email,
			...(brand.replyTo
				? {
					replyTo: brand.replyTo
				}
				: {}),
			idempotencyKey: [
				'device-verification',
				brand.applicationId,
				verification.id,
				verification.emailResendCount.toString(),
				verification.expiresAt.getTime().toString()
			].join('/'),
			tags: {
				application: brand.applicationId,
				category: 'device-verification'
			}
		});
	};
}

export default VerificationEmailService;
